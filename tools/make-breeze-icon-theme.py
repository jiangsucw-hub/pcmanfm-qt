#!/usr/bin/env python3
"""Turn the upstream breeze-icons SVG tree into an installable XDG icon theme.

The breeze-icons release tarball only ships the raw ``icons/<context>/<size>``
tree; ``index.theme`` is generated by its CMake build.  Qt's QIconLoader cannot
resolve a single icon without that file, so this script copies the tree and
writes an index.theme pointing at the real directory names.

Usage: make-breeze-icon-theme.py <source-icons-dir> <destination-theme-dir>
"""

import os
import re
import shutil
import sys

SIZE_RE = re.compile(r"^(\d+)(?:@(\d+)x)?$")


def theme_dirs(src):
    """Yield (relative directory, size in px, scale factor)."""
    for context in sorted(os.listdir(src)):
        context_dir = os.path.join(src, context)
        if not os.path.isdir(context_dir):
            continue
        for size_name in sorted(os.listdir(context_dir)):
            if not os.path.isdir(os.path.join(context_dir, size_name)):
                continue
            if size_name == "scalable":
                yield context, size_name, None, 1
                continue
            match = SIZE_RE.match(size_name)
            if not match:
                continue
            yield context, size_name, int(match.group(1)), int(match.group(2) or 1)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, dst = sys.argv[1], sys.argv[2]

    entries = list(theme_dirs(src))
    if not entries:
        sys.exit("no icon directories found in %s" % src)

    if os.path.isdir(dst):
        shutil.rmtree(dst)
    # the tree is full of symlinks; keeping them avoids ~130MB of duplicates
    shutil.copytree(src, dst, symlinks=True)

    directories = []
    sections = []
    for context, size_name, size, scale in entries:
        rel = "%s/%s" % (context, size_name)
        directories.append(rel)
        sections.append("[%s]" % rel)
        if size is None:  # scalable
            sections.append("Size=16")
            sections.append("MinSize=8")
            sections.append("MaxSize=512")
            sections.append("Type=Scalable")
        else:
            sections.append("Size=%d" % size)
            sections.append("Type=Fixed")
        if scale > 1:
            sections.append("Scale=%d" % scale)
        sections.append("Context=%s" % context.capitalize())
        sections.append("")

    index = ["[Icon Theme]",
             "Name=Breeze",
             "Comment=Breeze icon theme",
             "Inherits=hicolor",
             "Directories=%s" % ",".join(directories),
             ""]
    index.extend(sections)

    with open(os.path.join(dst, "index.theme"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(index))
    print("wrote %s (%d directories)" % (os.path.join(dst, "index.theme"), len(directories)))


if __name__ == "__main__":
    main()
